/** Rotating flash-deal strip (sample set, no invented stock numbers). */
export const flashDeals = products
  .filter((p) => p.discount >= 30)
  .sort((a, b) => b.discount - a.discount)
  .slice(0, 8)

/** "What everyone's buying" — ranked by sample popularity. */
export const trending = [...products].sort((a, b) => b.popularity - a.popularity).slice(0, 8)

/** Newest sample arrivals. */
export const newArrivals = [...products]
  .sort((a, b) => +new Date(b.addedAt) - +new Date(a.addedAt))
  .slice(0, 8)
